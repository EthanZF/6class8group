def _resolve_author(User):
    """按 超级用户 → 任意用户 → 新建不可登录用户 的顺序确定文章作者。"""
    user = User.objects.filter(is_superuser=True).order_by('id').first()
    if user:
        return user
    user = User.objects.order_by('id').first()
    if user:
        return user
    # 全新环境还没有任何用户：建一个不能登录的占位作者，避免数据迁移失败
    return User.objects.create(
        username='author',
        email='',
        password='!',   # Django 约定：以 ! 开头表示不可用密码，无法登录
        is_active=True,
    )


def apply(apps, schema_editor=None):
    """创建分类、标签与文章；重复执行不会产生重复数据。"""
    Category = apps.get_model('blog', 'Category')
    Tag = apps.get_model('blog', 'Tag')
    Article = apps.get_model('blog', 'Article')
    User = apps.get_model('accounts', 'BlogUser')

    # ---- 分类 ----
    cat_map = {}
    for name, parent_name in CATEGORIES:
        parent = cat_map.get(parent_name) if parent_name else None
        category, _ = Category.objects.get_or_create(
            name=name,
            defaults={
                'parent_category': parent,
                'slug': slugify(name),
                'index': 0,
            },
        )
        cat_map[name] = category

    # ---- 标签 ----
    tag_map = {}
    for name in TAGS:
        tag_map[name], _ = Tag.objects.get_or_create(
            name=name, defaults={'slug': slugify(name)})

    # ---- 文章 ----
    author = _resolve_author(User)
    base_time = timezone.now() - timedelta(days=len(ARTICLES))
    for offset, item in enumerate(ARTICLES):
        article, created = Article.objects.get_or_create(
            title=item['title'],
            defaults={
                'body': item['body'].strip(),
                'pub_time': base_time + timedelta(days=offset, hours=9),
                'status': 'p',
                'comment_status': 'o',
                'type': 'a',
                'author': author,
                'category': cat_map[item['category']],
                'article_order': 0,
                'show_toc': True,
                'views': 0,
                'is_top': False,
                'is_featured': False,
            },
        )
        if created:
            article.tags.set([tag_map[t] for t in item['tags']])


